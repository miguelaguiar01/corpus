// The write side of the built-in adapters (§3, §8): translations back
// into repo files, format-preserving so an unchanged catalog round-trips
// byte-identical. Pure: file contents in, file contents out.
//
// A messages file is edited in place (splice.ts): a changed value, a
// removed key or an added key touches only its own bytes, so a pull or
// a proposal reads as the lines it changes, whatever the file's layout.
// The base is the existing target file when there is one, else the
// source template. With an existing file, ids the translations do not
// mention keep their existing value; with only the template, they are
// omitted. A new id goes beside its neighbours in the source file
// (#654), at the key path the source file gives it (split on dots only
// when it holds none, nested when the file nests, flat when it is flat).
// TS-module sources are read-only here (see DECISIONS.md): only JSON
// files can be regenerated byte for byte.

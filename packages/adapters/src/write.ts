type Tree = { [key: string]: string | Tree };
type Style = { indent: string; trailingNewline: boolean };

const DEFAULT_STYLE: Style = { indent: "  ", trailingNewline: true };

function styleOf(text: string): Style {
  if (text.trim() === "") return DEFAULT_STYLE;
  const indented = /^([ \t]+)\S/m.exec(text);
  return {
    indent: indented?.[1] ?? DEFAULT_STYLE.indent,
    trailingNewline: text.endsWith("\n"),
  };
}

// Whether a file has an indented line, a layout to keep: `{}` has none.
export function hasIndentedLine(text: string): boolean {
  return /^[ \t]+\S/m.test(text);
}

// A target's indent: its own, or for one with no indented line, `{}`,
// the indent given, its sibling targets', else the source's (#1041).
function indentOf(text: string, template: string, given?: string): string {
  return hasIndentedLine(text)
    ? styleOf(text).indent
    : (given ?? styleOf(template).indent);
}

function parseTree(text: string): Tree {
  if (text.trim() === "") return {};
  const parsed: unknown = JSON.parse(stripBom(text));
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("messages: file must be a JSON object");
  }
  return parsed as Tree;
}

// A BOM is kept in the text, which the splice edits around; only
// JSON.parse refuses it.
export function stripBom(text: string): string {
  return text.startsWith("\uFEFF") ? text.slice(1) : text;
}

// A leaf's plural: none, an object of forms, or i18next's suffix keys,
// whose path is the family's, `item` for `item_one` (#985).
type Leaf = [
  path: string[],
  value: string,
  plural: false | "object" | "suffix",
];

// i18next's families: off, or on, a target's being `known`, the
// source's, a source's of its `language`'s categories (#985).
// `own`, the source's string ids, which a target's family never takes
// as a form (#1191).
type Suffix =
  | false
  | {
      known?: ReadonlySet<string>;
      language?: string;
      own?: ReadonlySet<string>;
    };

// With `plurals`, a plural object is one leaf, its text the plural
// string it reads as (#662); at an id of `known`, the source's plurals,
// one without `other` too (#950). With `suffix`, so is a family of
// i18next's plural keys, where its first form is written.
function leaves(
  tree: Tree,
  plurals: PluralObjects = false,
  known?: ReadonlySet<string>,
  suffix: Suffix = false,
  path: string[] = [],
  out: Leaf[] = [],
): Leaf[] {
  const families = suffix
    ? suffixFamilies(tree, path, suffix.known, suffix.language, suffix.own)
    : new Map<string, Map<string, string>>();
  const member = new Map<string, string>();
  for (const [base, forms] of families)
    for (const key of forms.values()) member.set(key, base);
  for (const [key, value] of Object.entries(tree)) {
    // A bare key beside its family is no translation of it, and is left.
    if (families.has(key)) continue;
    const base = member.get(key);
    if (base !== undefined) {
      const forms = families.get(base)!;
      if ([...forms.values()][0] === key)
        out.push([[...path, base], suffixText(tree, forms) ?? "", "suffix"]);
      continue;
    }
    const at = [...path, key];
    if (typeof value === "string") out.push([at, value, false]);
    else if (isPluralAt(value, at.join("."), plurals, known))
      out.push([at, pluralText("count", value, "written"), "object"]);
    // A list's items by index (#1053), an item's plural keys a family
    // as anywhere.
    else if (Array.isArray(value))
      leaves(value as unknown as Tree, plurals, known, suffix, at, out);
    // A null, number or boolean is no string, left as it is (#1026).
    else if (value !== null && typeof value === "object")
      leaves(value, plurals, known, suffix, at, out);
  }
  return out;
}

// The empty objects at ids the source holds as plurals, each by its key
// path: a target's plural with no form left, which a removal takes
// whole (#1148).
function emptyObjects(
  tree: Tree,
  known: ReadonlySet<string> | undefined,
): Map<string, string[]> {
  const out = new Map<string, string[]>();
  if (!known || known.size === 0) return out;
  const walk = (node: Tree, path: string[]) => {
    for (const [key, value] of Object.entries(node)) {
      if (typeof value !== "object" || value === null || Array.isArray(value))
        continue;
      const at = [...path, key];
      if (Object.keys(value).length === 0) {
        if (known.has(at.join("."))) out.set(at.join("."), at);
      } else walk(value, at);
    }
  };
  walk(tree, []);
  return out;
}

// Each id's key path as a file writes it, and the ids that are plural
// objects: a segment may hold dots (`"m.room.topic": { … }`), so an id
// is never split to find its place when a file already names it (#642).
function keyPaths(
  tree: Tree,
  plurals: PluralObjects = false,
  known?: ReadonlySet<string>,
  suffix: Suffix = false,
): {
  paths: Map<string, string[]>;
  pluralIds: Set<string>;
  suffixIds: Set<string>;
} {
  const found = leaves(tree, plurals, known, suffix);
  const ids = (kind: Leaf[2]) =>
    new Set(
      found
        .filter(([, , plural]) => plural === kind)
        .map(([path]) => path.join(".")),
    );
  return {
    paths: new Map(found.map(([path]) => [path.join("."), path])),
    pluralIds: ids("object"),
    suffixIds: ids("suffix"),
  };
}

// A plural's forms as an object in CLDR's order.
function inCldrOrder(forms: Record<string, string>): Record<string, string> {
  return Object.fromEntries(
    PLURAL_CATEGORIES.filter((c) => forms[c] !== undefined).map((c) => [
      c,
      forms[c]!,
    ]),
  );
}

// Why an id's text was not written, for the caller to say.
export type Refusal = (id: string, text: string) => void;

// The forms a translation of a plural object writes: its branches, or a
// plain text as the other form; undefined for a plural the object cannot
// hold, an `=0` branch or a brace a form leaves open, which would
// otherwise land whole in `other`. A target's needs no `other`, as its
// object may lack it (#950, #1188); a source's proposal does (#975).
function formsOf(
  text: string,
  needsOther = false,
): Record<string, string> | undefined {
  const forms = pluralBranches(text, needsOther);
  if (forms) return forms;
  // A plural with text beside it has nowhere to go but whole into
  // `other`, removing the rest (#1268).
  return /\{\s*[\p{L}_][\p{L}\p{M}\p{N}_.-]*\s*,\s*(?:plural|selectordinal)\s*,/u.test(
    text,
  )
    ? undefined
    : { other: text };
}

// A plural written as the object its file keeps (#662), through the
// document: each form of the text at `path.form`, in CLDR's order, and a
// form the text no longer has removed; a text that is not a plural is
// the `other` form. `current` is the value the file holds there, from
// the tree the caller parsed once (#1265); a string it replaces is
// rewritten on the text.
function writePlural(
  doc: JsonDoc,
  path: string[],
  plural: string,
  unit: string,
  current: unknown,
  order?: (objectPath: string[]) => string[] | undefined,
  onRefused?: Refusal,
  needsOther = false,
  // Read from the text, as the sequential oracle does, or where a write
  // before it reached its path, which the parse no longer holds.
  onText = false,
): void {
  if (onText || typeof current === "string") {
    doc.apply((text) =>
      writePluralText(text, path, plural, unit, order, onRefused, needsOther),
    );
    return;
  }
  const forms = formsOf(plural, needsOther);
  if (!forms) {
    onRefused?.(path.join("."), plural);
    return;
  }
  const at = path.join("\u0000");
  const inOrder = (objectPath: string[]) =>
    objectPath.join("\u0000") === at
      ? [...PLURAL_CATEGORIES]
      : order?.(objectPath);
  for (const form of PLURAL_CATEGORIES) {
    const value = forms[form];
    if (value === undefined) continue;
    const leaf = [...path, form];
    if (!doc.edit(leaf, value)) doc.add(leaf, value, unit, inOrder);
  }
  if (current && typeof current === "object")
    for (const form of Object.keys(current))
      if (!Object.hasOwn(forms, form)) doc.remove([...path, form]);
}

// The paths a run's writes reached, so a plural knows whether the parse
// before them still holds its value: none at it, above it or under it.
class Reached {
  private at = new Set<string>();
  private above = new Set<string>();
  add(path: string[]): void {
    this.at.add(path.join("\u0000"));
    for (let k = 1; k < path.length; k++)
      this.above.add(path.slice(0, k).join("\u0000"));
  }
  // A family's keys, `base_one` and the rest, which its write reaches.
  addFamily(path: string[]): void {
    const parent = path.slice(0, -1);
    const base = path[path.length - 1]!;
    for (const form of PLURAL_CATEGORIES)
      this.add([...parent, `${base}_${form}`]);
  }
  near(path: string[]): boolean {
    if (this.above.has(path.join("\u0000"))) return true;
    for (let k = 1; k <= path.length; k++)
      if (this.at.has(path.slice(0, k).join("\u0000"))) return true;
    return false;
  }
}

// The same, on the text, reading what it holds at `path` from it.
function writePluralText(
  text: string,
  path: string[],
  plural: string,
  unit: string,
  order?: (objectPath: string[]) => string[] | undefined,
  onRefused?: Refusal,
  needsOther = false,
): string {
  const forms = formsOf(plural, needsOther);
  if (!forms) {
    onRefused?.(path.join("."), plural);
    return text;
  }
  const at = path.join("\u0000");
  const inOrder = (objectPath: string[]) =>
    objectPath.join("\u0000") === at
      ? [...PLURAL_CATEGORIES]
      : order?.(objectPath);
  let current: unknown = parseTree(text);
  for (const key of path)
    current =
      current && typeof current === "object"
        ? (current as Tree)[key]
        : undefined;
  // A string the forms replace is replaced where it stands, in the
  // line style of the object it is in (#1235).
  if (typeof current === "string")
    return replaceValue(
      text,
      path,
      {
        json: inCldrOrder(forms),
      },
      unit,
    );
  let out = text;
  for (const form of PLURAL_CATEGORIES) {
    const value = forms[form];
    if (value === undefined) continue;
    const leaf = [...path, form];
    out =
      editLeaf(out, leaf, value) ?? addLeaf(out, leaf, value, unit, inOrder);
  }
  if (current && typeof current === "object")
    for (const form of Object.keys(current))
      if (!Object.hasOwn(forms, form)) out = deleteLeaf(out, [...path, form]);
  return out;
}

// A plural written as i18next's suffix keys (#985): each form of the
// text at `base_<category>` beside the family's other keys, a new one
// where CLDR's order puts it among them. A form the text lacks is left
// as the file has it, one the language never picks included, save in a
// file written afresh, `fresh`, where it goes.
function writeSuffix(
  doc: JsonDoc,
  path: string[],
  plural: string,
  unit: string,
  fresh: boolean,
  order?: (objectPath: string[]) => string[] | undefined,
  onRefused?: Refusal,
  needsOther = false,
): void {
  const forms = formsOf(plural, needsOther);
  if (!forms) {
    onRefused?.(path.join("."), plural);
    return;
  }
  const parent = path.slice(0, -1);
  const base = path[path.length - 1]!;
  const keys = PLURAL_CATEGORIES.map((c) => `${base}_${c}`);
  const at = parent.join("\u0000");
  const inOrder = (objectPath: string[]) => {
    const own = order?.(objectPath);
    if (objectPath.join("\u0000") !== at) return own;
    const list = own ?? [];
    const first = list.findIndex((k) => keys.includes(k));
    const rest = list.filter((k) => !keys.includes(k));
    rest.splice(first < 0 ? rest.length : first, 0, ...keys);
    return rest;
  };
  for (const [i, form] of PLURAL_CATEGORIES.entries()) {
    const leaf = [...parent, keys[i]!];
    const value = forms[form];
    if (value !== undefined) {
      if (!doc.edit(leaf, value)) doc.add(leaf, value, unit, inOrder);
    } else if (fresh) doc.remove(leaf);
  }
}

// A family of suffix keys removed whole: whether any was there.
function deleteSuffix(doc: JsonDoc, path: string[]): boolean {
  const parent = path.slice(0, -1);
  const base = path[path.length - 1]!;
  let removed = false;
  for (const form of PLURAL_CATEGORIES)
    removed = doc.remove([...parent, `${base}_${form}`]) || removed;
  return removed;
}

function isNested(tree: Tree): boolean {
  return Object.values(tree).some((value) => typeof value !== "string");
}

function setPath(tree: Tree, path: string[], value: string): void {
  checkPath(path);
  const own = (at: Tree, key: string) =>
    Object.hasOwn(at, key) ? at[key] : undefined;
  let node = tree;
  for (const key of path.slice(0, -1)) {
    const next = own(node, key);
    if (typeof next === "string") {
      // A literal sits where nesting would go: a flat key at the root, as
      // the splice writes it, so the id reads back as itself.
      const flat = path.join(".");
      if (typeof own(tree, flat) === "object") collision(flat);
      tree[flat] = value;
      return;
    }
    node = next ?? (node[key] = Object.create(null) as Tree);
  }
  const last = path[path.length - 1]!;
  if (typeof own(node, last) === "object") collision(path.join("."));
  node[last] = value;
}

// An id equal to a nested key path cannot live in this file's shape;
// failing loudly beats overwriting the subtree.
function collision(id: string): never {
  throw new Error(
    `messages: id ${JSON.stringify(id)} collides with a nested key path`,
  );
}

// `locale` is an .arb's language. A missing .json is the template with
// the strings swapped and the rest deleted, which for an .arb would leave
// the source's `@@locale` and the shells of its `@key` metadata behind;
// a missing .arb is written from the template's strings alone, with
// `@@locale` first, since gen-l10n reads the locale from it before the
// file name (#568), in the underscore form: gen-l10n compares `@@locale`
// as written with the file name's locale normalised to underscores and
// refuses a mismatch, so `pt-PT` is written `pt_PT` whatever the file
// name says (#585). The `@key` metadata stays in the source, where
// gen-l10n reads it.
export function entriesToMessages(
  template: string,
  translations: Record<string, string>,
  existing?: string,
  options: {
    locale?: string;
    chrome?: boolean;
    // Entry objects (#1001): the translation goes into the text field.
    entries?: { text: string };
    plurals?: PluralObjects;
    // i18next's plural keys are one string (#985), a source's of the
    // categories its language picks.
    suffixPlurals?: boolean;
    sourceLanguage?: string;
    onRefused?: Refusal;
    // A translation for a list the file holds, which Corpus does not
    // read and leaves as it is (#1026).
    onList?: (id: string) => void;
    // The indent an empty target takes, its sibling targets' (#1041);
    // the source's where none is given.
    indent?: string;
    // Each change spliced in on its own, as before #693: the oracle the
    // batched writes are tested against.
    sequential?: boolean;
  } = {},
): string {
  translations = ownRecord(translations);
  const sequential = options.sequential ?? false;
  if (options.chrome)
    return chromeMessages(
      template,
      translations,
      existing,
      options.indent,
      sequential,
    );
  if (options.entries)
    return entryMessages(
      template,
      translations,
      existing,
      options.entries.text,
      options.onRefused,
      options.indent,
      sequential,
    );
  const plurals = options.plurals ?? false;
  const suffix: Suffix = options.suffixPlurals
    ? { ...(options.sourceLanguage && { language: options.sourceLanguage }) }
    : false;
  const onRefused = options.onRefused;
  // A blank target of a source that holds lists is written as a missing
  // one is, from the source's text, which a list's items need (#1053).
  const blank = existing !== undefined && existing.trim() === "";
  const listed =
    blank &&
    options.locale === undefined &&
    template.trim() !== "" &&
    listsOf(parseTree(template)).length > 0;
  if (listed) existing = undefined;
  const base = existing !== undefined ? existing : template;
  const missing = existing === undefined || existing.trim() === "";
  if (base.trim() === "" || (missing && options.locale !== undefined))
    return fromTemplate(
      template,
      translations,
      options.locale,
      plurals,
      onRefused,
      suffix,
    );
  const baseTree = parseTree(base);
  const style = {
    ...styleOf(base),
    indent: indentOf(base, template, options.indent),
  };
  const nested = isNested(baseTree);
  const sourceTree = parseTree(template);
  const {
    paths: sourcePaths,
    pluralIds: sourcePlurals,
    suffixIds: sourceSuffix,
  } = keyPaths(sourceTree, plurals, undefined, suffix);
  const order = keyOrder(stripBom(template));
  const fresh = existing === undefined;
  const doc = jsonDoc(base, sequential);
  const seen = new Set<string>();
  // As the reader takes them: a target's plural in either shape, an
  // object or suffix keys, wherever the source has one in either, and
  // written back in the target's own (#1187); a new file is the
  // source's, read as the source is.
  const known = new Set([...sourcePlurals, ...sourceSuffix]);
  // The source's strings, none of which a target's family takes (#1191).
  const own = new Set([...sourcePaths.keys()].filter((id) => !known.has(id)));
  // A list is one value whose items are numbered (#1053): in a new
  // file it runs to its last translated item, the source's text before
  // it, and goes where none is translated.
  const sourceLists = listsOf(sourceTree);
  const lastWritten = new Map<string, number>();
  for (const id of Object.keys(translations)) {
    const path = sourcePaths.get(id);
    const list = path && listOf(sourceLists, path);
    if (!list) continue;
    const key = list.join("\u0000");
    lastWritten.set(
      key,
      Math.max(lastWritten.get(key) ?? -1, Number(path[list.length])),
    );
  }
  const reached = new Reached();
  for (const [path, value, plural] of leaves(
    baseTree,
    plurals,
    fresh ? sourcePlurals : known,
    suffix && { ...suffix, known: fresh ? sourceSuffix : known, own },
  )) {
    const id = path.join(".");
    seen.add(id);
    const next = translations[id];
    const list = fresh ? listOf(sourceLists, path) : undefined;
    if (list) {
      // Past the last item written it goes with the cut; before it an
      // untranslated one keeps the source's text; a translation is
      // written as anywhere, a plural as a plural.
      const last = lastWritten.get(list.join("\u0000")) ?? -1;
      if (Number(path[list.length]) > last || next === undefined) continue;
    }
    if (next !== undefined) {
      if (next === value) continue;
      // A list's item that is a string where the source has a plural
      // object is replaced in place: removing it would renumber the
      // items after it (#1053).
      const item =
        !plural &&
        sourcePlurals.has(id) &&
        nodeAt(parseTreeNode(doc.text()), path.slice(0, -1))?.type === "array";
      if (item) {
        const forms = formsOf(next);
        if (forms)
          doc.apply((text) =>
            replaceValue(
              text,
              path,
              {
                json: inCldrOrder(forms),
              },
              style.indent,
            ),
          );
        else onRefused?.(id, next);
        reached.add(path);
        continue;
      }
      // In a new file a plural it cannot hold goes, as an untranslated
      // one does, rather than keep the source's forms (#1189); in a
      // list's item, as an untranslated one there, it keeps them.
      const held = !(plural || sourcePlurals.has(id)) || formsOf(next);
      if (fresh && !held && !list) {
        onRefused?.(id, next);
        if (plural === "suffix") deleteSuffix(doc, path);
        else doc.remove(path, true);
      } else if (plural === "suffix")
        writeSuffix(doc, path, next, style.indent, fresh, order, onRefused);
      else if (plural || sourcePlurals.has(id))
        writePlural(
          doc,
          path,
          next,
          style.indent,
          valueAt(baseTree, path),
          order,
          onRefused,
          false,
          sequential || reached.near(path),
        );
      else doc.edit(path, next);
    } else if (fresh) {
      if (plural === "suffix") deleteSuffix(doc, path);
      else doc.remove(path, plural !== false);
    }
    reached.add(path);
    if (plural === "suffix") reached.addFamily(path);
  }
  if (fresh)
    for (const list of sourceLists) {
      const last = lastWritten.get(list.join("\u0000"));
      doc.apply((text) =>
        last === undefined
          ? deleteKey(text, list)
          : truncateList(text, list, last + 1),
      );
    }
  const lists = listIds(baseTree);
  // The source's lists a target lacks, or holds short, by their items
  // to write (#1053).
  const underLists: string[] = [];
  for (const id of Object.keys(translations)) {
    if (seen.has(id)) continue;
    const inSource = sourcePaths.get(id);
    if (inSource && listOf(sourceLists, inSource)) {
      underLists.push(id);
      continue;
    }
    const parts = id.split(".");
    if (parts.some((_, i) => lists.has(parts.slice(0, i + 1).join(".")))) {
      options.onList?.(id);
      continue;
    }
    const path = sourcePaths.get(id) ?? (nested ? id.split(".") : [id]);
    const next = translations[id]!;
    if (sourceSuffix.has(id))
      writeSuffix(doc, path, next, style.indent, fresh, order, onRefused);
    else if (sourcePlurals.has(id))
      writePlural(
        doc,
        path,
        next,
        style.indent,
        valueAt(baseTree, path),
        order,
        onRefused,
        false,
        sequential || reached.near(path),
      );
    else doc.add(path, next, style.indent, order);
    reached.add(path);
    if (sourceSuffix.has(id)) reached.addFamily(path);
  }
  if (underLists.length > 0)
    completeLists(
      doc,
      underLists,
      sourceTree,
      sourcePaths,
      sourceSuffix,
      {
        translations,
        pluralIds: sourcePlurals,
        ...(options.sourceLanguage && { language: options.sourceLanguage }),
        ...(onRefused && { onRefused }),
      },
      style.indent,
      order,
      (id) => options.onList?.(id),
    );
  return doc.text();
}

// The highest of the numbers, -1 for none: `Math.max(...numbers)`
// overflows the stack past about 120,000 of them (#1276).
function highest(numbers: number[]): number {
  let out = -1;
  for (const n of numbers) if (n > out) out = n;
  return out;
}

// The outermost lists of a file, by key path (#1053).
function listsOf(
  tree: unknown,
  path: string[] = [],
  out: string[][] = [],
): string[][] {
  if (Array.isArray(tree)) out.push(path);
  else if (tree !== null && typeof tree === "object")
    for (const [key, value] of Object.entries(tree))
      listsOf(value, [...path, key], out);
  return out;
}

// The list a key path is an item of, or inside one.
function listOf(lists: string[][], path: string[]): string[] | undefined {
  return lists.find(
    (list) =>
      list.length < path.length && list.every((key, i) => path[i] === key),
  );
}

function valueAt(tree: unknown, path: string[]): unknown {
  let node = tree;
  for (const key of path) {
    if (node === null || typeof node !== "object") return undefined;
    node = (node as Record<string, unknown>)[key];
  }
  return node;
}

// The context a list's missing parts are built in (#1053): the
// translations, the source's plural objects and families, and where a
// plural that cannot be held is said.
type Fill = {
  translations: Record<string, string>;
  pluralIds: ReadonlySet<string>;
  language?: string;
  onRefused?: Refusal;
};

// The forms of a plural translation in CLDR's order, or undefined where
// it cannot be held, said through `onRefused`.
function formsFor(
  fill: Fill,
  id: string,
  text: string,
): Record<string, string> | undefined {
  const forms = formsOf(text);
  if (!forms) {
    fill.onRefused?.(id, text);
    return undefined;
  }
  return inCldrOrder(forms);
}

// The source's value at `path` as the target writes it: its strings the
// translations where given, a plural object's or a family's forms the
// translation's, its numbers kept. `leading` given, only what leads to
// those ids: an object's other keys left out, a list up to the last item
// they reach, its items whole; a part that leads to none is undefined.
function buildFrom(
  value: unknown,
  path: string[],
  fill: Fill,
  leading?: string[][],
): unknown {
  const id = path.join(".");
  const reaches = (at: string[]) =>
    !leading ||
    leading.some(
      (p) => p.length >= at.length && at.every((seg, i) => p[i] === seg),
    );
  if (leading && !reaches(path)) return undefined;
  const given = fill.translations[id];
  if (fill.pluralIds.has(id)) {
    const forms = given === undefined ? undefined : formsFor(fill, id, given);
    return forms ?? (leading ? undefined : value);
  }
  if (typeof value === "string") return given ?? (leading ? undefined : value);
  if (Array.isArray(value)) {
    const last = leading
      ? highest(
          leading
            .filter(
              (p) =>
                p.length > path.length && path.every((seg, i) => p[i] === seg),
            )
            .map((p) => Number(p[path.length])),
        )
      : value.length - 1;
    // An empty list copied whole is itself, holding its place.
    if (last < 0) return leading ? undefined : [];
    return value
      .slice(0, last + 1)
      .map((item, i) => buildFrom(item, [...path, String(i)], fill));
  }
  if (value !== null && typeof value === "object") {
    const record = value as Record<string, unknown>;
    const families = suffixFamilies(record, path, undefined, fill.language);
    const member = new Map<string, string>();
    for (const [base, forms] of families)
      for (const key of forms.values()) member.set(key, base);
    const out: Record<string, unknown> = Object.create(null);
    for (const [key, child] of Object.entries(record)) {
      const base = member.get(key);
      if (base !== undefined) {
        // A family is written once, where its first form is.
        const forms = families.get(base)!;
        if ([...forms.values()][0] !== key) continue;
        const familyId = [...path, base].join(".");
        const text = fill.translations[familyId];
        const written =
          text === undefined ? undefined : formsFor(fill, familyId, text);
        if (written)
          for (const [form, t] of Object.entries(written))
            out[`${base}_${form}`] = t;
        else if (!leading) for (const k of forms.values()) out[k] = record[k];
        continue;
      }
      const built = buildFrom(child, [...path, key], fill, leading);
      if (built !== undefined) out[key] = built;
    }
    return leading && Object.keys(out).length === 0 ? undefined : out;
  }
  return leading ? undefined : value;
}

// The translations under a source's list a target does not hold: each
// walked down the target along its path to the first part the target
// lacks, which is written built from the source's (a list's missing
// items appended, an object or a list it lacks added whole), a plural
// there written as one; a part the target holds in another shape than
// the source's is named and left, as is one no write could place
// (#1053).
function completeLists(
  doc: JsonDoc,
  ids: string[],
  sourceTree: Tree,
  sourcePaths: Map<string, string[]>,
  suffixIds: ReadonlySet<string>,
  fill: Fill,
  indent: string,
  order: ReturnType<typeof keyOrder>,
  onList: (id: string) => void,
): void {
  // What a write refused is said once, by the refusal.
  const refused = new Set<string>();
  const said = fill.onRefused;
  fill = {
    ...fill,
    onRefused: (id, value) => {
      refused.add(id);
      said?.(id, value);
    },
  };
  const name = (id: string) => {
    if (!refused.has(id)) onList(id);
  };
  // Each id's first missing part, grouped so a list or an object is
  // written once for every id it holds: a list's missing items by the
  // list, whatever order their translations come in.
  const groups = new Map<string, { at: string[]; ids: string[] }>();
  const tree = parseTreeNode(doc.text());
  for (const id of ids) {
    const path = sourcePaths.get(id)!;
    // A family's base is no key of its own: its parent is the leaf's.
    const leafParent = suffixIds.has(id) ? path.length - 1 : path.length;
    let node = tree;
    let at: string[] | undefined;
    let mismatch = false;
    let appending = false;
    for (let k = 0; k < leafParent; k++) {
      const child = node && nodeAt(node, [path[k]!]);
      if (!child) {
        at = path.slice(0, k + 1);
        appending = node?.type === "array";
        break;
      }
      const source = valueAt(sourceTree, path.slice(0, k + 1));
      const container = Array.isArray(source)
        ? "array"
        : source !== null && typeof source === "object"
          ? "object"
          : "string";
      if (k < leafParent - 1 && child.type !== container) {
        mismatch = true;
        break;
      }
      node = child;
    }
    // A family goes into an object, never a string or a list an item is.
    if (!at && suffixIds.has(id) && node?.type !== "object") mismatch = true;
    if (mismatch) {
      onList(id);
      continue;
    }
    // Every part held but the leaf: the leaf goes in as a leaf.
    const leafAt = at
      ? appending
        ? at.slice(0, -1)
        : at
      : path.slice(0, leafParent);
    const key =
      (at ? (appending ? "append\u0000" : "part\u0000") : "leaf\u0000") +
      leafAt.join("\u0000");
    // A list's missing items are kept by the list's own path.
    const group = groups.get(key) ?? {
      at: appending ? leafAt : (at ?? path),
      ids: [],
    };
    group.ids.push(id);
    groups.set(key, group);
  }
  for (const [key, { at, ids: held }] of groups) {
    if (key.startsWith("leaf\u0000")) {
      doc.apply((original) => {
        let text = original;
        for (const id of held) {
          const path = sourcePaths.get(id)!;
          const next = fill.translations[id]!;
          const was = text;
          const leaf = nodeAt(parseTreeNode(text), path);
          if (suffixIds.has(id)) {
            const doc = jsonDoc(text, true);
            writeSuffix(doc, path, next, indent, false, order, fill.onRefused);
            text = doc.text();
          } else if (fill.pluralIds.has(id) && leaf?.type === "object")
            text = writePluralText(
              text,
              path,
              next,
              indent,
              order,
              fill.onRefused,
            );
          // A string where the source has a plural becomes the plural, as
          // it does outside a list (#1187).
          else if (fill.pluralIds.has(id) && leaf?.type === "string") {
            const forms = formsFor(fill, id, next);
            if (forms) text = replaceValue(text, path, { json: forms }, indent);
          }
          // A plain string the target holds every part of, the leaf too,
          // and did not read, or a list where the source has a plural: a
          // shape the source does not have there.
          if (text === was) name(id);
        }
        return text;
      });
      continue;
    }
    const leading = held.map((id) => sourcePaths.get(id)!);
    // What a write leaves as it was is named, each id it held.
    const written = (write: (text: string) => string) =>
      doc.apply((text) => {
        const out = write(text);
        if (out === text) for (const id of held) name(id);
        return out;
      });
    if (key.startsWith("append\u0000")) {
      // Items the target's list lacks, from its length to the last one
      // these ids reach, appended whole.
      const list = valueAt(sourceTree, at);
      const heldItems = nodeAt(tree, at)?.children?.length ?? 0;
      const last = highest(leading.map((p) => Number(p[at.length])));
      const values: unknown[] = [];
      if (Array.isArray(list))
        for (let i = heldItems; i <= last; i++)
          values.push(buildFrom(list[i], [...at, String(i)], fill));
      written((text) => appendItems(text, at, values, indent));
      continue;
    }
    const value = buildFrom(valueAt(sourceTree, at), at, fill, leading);
    if (value === undefined) for (const id of held) name(id);
    // A string into an object goes through the document, batched (#1290).
    else if (
      typeof value === "string" &&
      nodeAt(tree, at.slice(0, -1))?.type === "object"
    )
      doc.add(at, value, indent, order);
    else written((text) => addLeaf(text, at, { json: value }, indent, order));
  }
}

function listIds(
  tree: unknown,
  path: string[] = [],
  out = new Set<string>(),
): Set<string> {
  if (Array.isArray(tree)) out.add(path.join("."));
  else if (tree !== null && typeof tree === "object")
    for (const [key, value] of Object.entries(tree))
      listIds(value, [...path, key], out);
  return out;
}

// Chrome i18n (#595): a translation is an entry's `message`, edited in
// place; the rest of the entry is the source's, copied with a new key.
// A missing or blank file starts from the source, BOM and all.
// Entry objects (#1001): a translation goes into an entry's text field,
// every other byte kept, and a new entry, in a file new or not, is the
// text field alone, as Signal's targets hold theirs. A value that is no
// entry is the file's, refused and left.
function entryMessages(
  template: string,
  translations: Record<string, string>,
  existing: string | undefined,
  field: string,
  onRefused?: Refusal,
  given?: string,
  sequential = false,
): string {
  if (existing === undefined || existing.trim() === "") {
    const style = styleOf(template);
    const out: Tree = Object.create(null) as Tree;
    const order = [
      ...Object.keys(parseTree(template)),
      ...Object.keys(translations),
    ];
    for (const id of order)
      if (Object.hasOwn(translations, id) && !Object.hasOwn(out, id))
        out[id] = { [field]: translations[id]! };
    return likeFile(
      JSON.stringify(out, null, style.indent) +
        (style.trailingNewline ? "\n" : ""),
      template,
    );
  }
  const doc = jsonDoc(existing, sequential);
  const base = parseTree(existing);
  const indent = indentOf(existing, template, given);
  for (const [id, next] of Object.entries(translations)) {
    if (!Object.hasOwn(base, id)) {
      doc.add([id, field], next, indent);
      continue;
    }
    const entry = base[id];
    const current =
      entry !== null && typeof entry === "object" && !Array.isArray(entry)
        ? (entry as Record<string, unknown>)[field]
        : entry;
    if (
      entry === null ||
      typeof entry !== "object" ||
      Array.isArray(entry) ||
      (current !== undefined && typeof current !== "string")
    ) {
      onRefused?.(id, next);
      continue;
    }
    if (current === next) continue;
    if (!doc.edit([id, field], next)) doc.add([id, field], next, indent);
  }
  return doc.text();
}

// Chrome's `{ message }` entries (#595): a new one takes the source's
// description and placeholders, which Chrome reads in every language.
function chromeMessages(
  template: string,
  translations: Record<string, string>,
  existing: string | undefined,
  given?: string,
  sequential = false,
): string {
  const field = "message";
  const fresh = existing === undefined || existing.trim() === "";
  const text = fresh ? template : existing;
  const doc = jsonDoc(text, sequential);
  const source = parseTree(template);
  const base = parseTree(text);
  const indent = indentOf(text, template, given);
  for (const [id, entry] of Object.entries(base)) {
    const next = Object.hasOwn(translations, id) ? translations[id] : undefined;
    if (next === undefined) {
      if (fresh) doc.remove([id], true);
    } else if (typeof entry !== "object" || entry[field] !== next) {
      if (!doc.edit([id, field], next)) doc.add([id, field], next, indent);
    }
  }
  for (const [id, next] of Object.entries(translations)) {
    if (Object.hasOwn(base, id)) continue;
    const model = source[id];
    const fields: [string[], string][] =
      typeof model === "object"
        ? leaves(model).map(([path, value]) => [path, value])
        : [[[field], next]];
    for (const [path, value] of fields)
      doc.add([id, ...path], path.join(".") === field ? next : value, indent);
  }
  return doc.text();
}

// An empty file has no bytes to keep: the template's structure and
// style, rewritten, as the first pull into a new target file.
function fromTemplate(
  template: string,
  translations: Record<string, string>,
  locale?: string,
  plurals: PluralObjects = false,
  onRefused?: Refusal,
  suffix: Suffix = false,
): string {
  const style = styleOf(template);
  const tree = parseTree(template);
  const nested = isNested(tree);
  const out: Tree = Object.create(null) as Tree;
  if (locale !== undefined) out["@@locale"] = locale.replaceAll("-", "_");
  const seen = new Set<string>();
  for (const [path, , plural] of leaves(tree, plurals, undefined, suffix)) {
    const id = path.join(".");
    seen.add(id);
    const value = translations[id];
    if (value === undefined) continue;
    if (!plural) setPath(out, path, value);
    else {
      const forms = formsOf(value);
      if (!forms) {
        onRefused?.(id, value);
        continue;
      }
      // An object's forms under its key; a family's beside each other.
      const at = (form: string) =>
        plural === "suffix"
          ? [...path.slice(0, -1), `${path[path.length - 1]}_${form}`]
          : [...path, form];
      for (const form of PLURAL_CATEGORIES)
        if (forms[form] !== undefined) setPath(out, at(form), forms[form]);
    }
  }
  for (const id of Object.keys(translations)) {
    if (seen.has(id)) continue;
    setPath(out, nested ? id.split(".") : [id], translations[id]!);
  }
  // The template's line endings and BOM (#850).
  return likeFile(
    JSON.stringify(out, null, style.indent) +
      (style.trailingNewline ? "\n" : ""),
    template,
  );
}

// JSON written as `like` is: its line endings and its BOM. JSON escapes
// a line break inside a string, so every one here is the layout's.
function likeFile(json: string, like: string): string {
  const bom = like.startsWith("\uFEFF") ? "\uFEFF" : "";
  return bom + json.replace(/\n/g, eolOf(like));
}

type Record_ = Record<string, unknown>;

function parseRecords(text: string): Record_[] {
  if (text.trim() === "") return [];
  const parsed: unknown = JSON.parse(stripBom(text));
  if (!Array.isArray(parsed))
    throw new Error("table: file must be a JSON array");
  return parsed as Record_[];
}

// Two record layouts are recognised: one record per line, or fully
// expanded (JSON.stringify's). Anything else is rewritten as expanded.
function oneRecordPerLine(text: string, count: number): boolean {
  const lines = text.trim().split("\n");
  return count > 0 && lines.length === count + 2;
}

function inlineRecord(record: Record_): string {
  const fields = Object.entries(record).map(
    ([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`,
  );
  return fields.length ? `{ ${fields.join(", ")} }` : "{}";
}

export function entriesToTable(
  template: string,
  translations: Record<string, string>,
  map: { id: string; text: string },
  existing?: string,
): string {
  translations = ownRecord(translations);
  // A blank file is a new one: the template's layout, line endings and
  // BOM (#883).
  if (existing?.trim() === "") existing = undefined;
  // One with no records keeps its own BOM and line endings but takes the
  // template's layout, which `[]` cannot show, and is left as it is when
  // nothing goes into it (#927).
  const empty = existing !== undefined && parseRecords(existing).length === 0;
  const fresh = existing === undefined || empty;
  const base = fresh ? template : existing!;
  const style = styleOf(base);
  const baseRecords = parseRecords(base);
  const inline = oneRecordPerLine(base, baseRecords.length);

  const out: Record_[] = [];
  const seen = new Set<string>();
  const emit = (record: Record_, fallback: boolean) => {
    const id = String(record[map.id]);
    seen.add(id);
    const text = translations[id];
    if (text === undefined && !fallback) return;
    out.push({ ...record, [map.text]: text ?? record[map.text] });
  };
  for (const record of baseRecords) emit(record, !fresh);
  if (!fresh) {
    for (const record of parseRecords(template)) {
      if (!seen.has(String(record[map.id]))) emit(record, false);
    }
  }

  if (!empty) return renderRecords(out, style, inline, base);
  if (out.length === 0) return existing!;
  const own = existing!.startsWith("\uFEFF") ? "\uFEFF" : "";
  return renderRecords(
    out,
    style,
    inline,
    own + eolOf(existing!.includes("\n") ? existing! : template),
  );
}

// A table's records in the file's layout: one record a line where the
// file writes them so, else JSON's own, written as `like` is (#883).
function renderRecords(
  records: Record_[],
  style: Style,
  inline: boolean,
  like: string,
): string {
  // No records is `[]`, whose layout no pull could tell again.
  const body =
    inline && records.length > 0
      ? `[\n${records.map((r) => style.indent + inlineRecord(r)).join(",\n")}\n]`
      : JSON.stringify(records, null, style.indent);
  return likeFile(body + (style.trailingNewline ? "\n" : ""), like);
}

// Source-side operations (§8, §11): a proposal sets, adds or removes a
// key in the source-language file, and a removal leaves the target
// files too, each touching only its own bytes. An edit of an absent id
// adds it; a delete of an absent id is nothing.
export type SourceOp =
  | { kind: "edit" | "add"; id: string; text: string }
  | { kind: "delete"; id: string };

export function applyMessagesOps(
  text: string,
  ops: SourceOp[],
  options: {
    chrome?: boolean;
    entries?: { text: string };
    plurals?: PluralObjects;
    // A target file's: the ids its source holds as plurals, which its
    // own objects are, whatever their forms (#984), and its families.
    pluralIds?: ReadonlySet<string>;
    // i18next's plural keys are one string (#985).
    suffixPlurals?: boolean;
    sourceLanguage?: string;
    // A target file's: the source's strings shaped as a family's form,
    // which are none of its families' (#1191).
    ownIds?: ReadonlySet<string>;
    // The oracle the batched writes are tested against (#693).
    sequential?: boolean;
  } = {},
): string {
  if (text.trim() === "") text = "{}\n";
  const sequential = options.sequential ?? false;
  if (options.chrome) return chromeOps(text, ops, "message", sequential);
  if (options.entries)
    return chromeOps(text, ops, options.entries.text, sequential);
  const tree = parseTree(text);
  const nested = isNested(tree);
  const plurals = options.plurals ?? false;
  const suffix = options.suffixPlurals ?? false;
  const { paths, pluralIds, suffixIds } = keyPaths(
    tree,
    plurals,
    options.pluralIds,
    suffix && {
      ...(options.pluralIds && { known: options.pluralIds }),
      ...(options.sourceLanguage && { language: options.sourceLanguage }),
      ...(options.ownIds && { own: options.ownIds }),
    },
  );
  // A new plural is written as the file writes its others: as keys, or
  // as objects in a file that holds objects and no families.
  const asObjects = pluralIds.size > 0 && suffixIds.size === 0;
  const newPlural = (op: SourceOp & { text: string }) =>
    !paths.has(op.id) && pluralBranches(op.text) !== undefined;
  const { indent } = styleOf(text);
  const refuse = (id: string) => {
    throw new Error(
      `messages: ${id} is a plural its object cannot hold (an =N branch, or a brace a form leaves open)`,
    );
  };
  const doc = jsonDoc(text, sequential);
  const lists = listsOf(tree);
  const empty = emptyObjects(tree, options.pluralIds);
  const reached = new Reached();
  for (const op of ops) {
    const path =
      paths.get(op.id) ??
      (op.kind === "delete" ? empty.get(op.id) : undefined) ??
      (nested ? op.id.split(".") : [op.id]);
    // A list's items are numbered: adding or removing one renumbers the
    // ids after it, so only an edit of one it holds is written (#1053).
    // A removal of an id the file does not hold is nothing to do.
    if (listOf(lists, path) && op.kind === "delete" && !paths.has(op.id))
      continue;
    if (listOf(lists, path) && (op.kind === "delete" || !paths.has(op.id)))
      throw new Error(
        `messages: ${op.id} is an item of a list, which a proposal cannot add or remove: it would renumber the items after it`,
      );
    if (op.kind === "delete") {
      // Absent already (a second pull, a target file without the key):
      // nothing to do; the push that lands the removal marks it applied.
      const removed = suffixIds.has(op.id)
        ? deleteSuffix(doc, path)
        : doc.remove(path, pluralIds.has(op.id) || empty.has(op.id));
      if (suffixIds.has(op.id)) reached.addFamily(path);
      if (!removed) doc.remove([op.id]);
    } else if (
      suffixIds.has(op.id) ||
      (suffix && !asObjects && newPlural(op))
    ) {
      // A proposed plural, edited or new, is the source's whole plural:
      // a form it lacks goes (#985).
      writeSuffix(doc, path, op.text, indent, true, undefined, refuse, true);
      reached.addFamily(path);
    } else if (pluralIds.has(op.id) || (suffix && asObjects && newPlural(op))) {
      // A proposal the object cannot hold fails the file loudly: it is
      // counted written otherwise, and never lands.
      writePlural(
        doc,
        path,
        op.text,
        indent,
        valueAt(tree, path),
        undefined,
        refuse,
        true,
        sequential || reached.near(path),
      );
    } else if (!doc.edit(path, op.text)) doc.add(path, op.text, indent);
    reached.add(path);
  }
  return doc.text();
}

function chromeOps(
  text: string,
  ops: SourceOp[],
  field: string,
  sequential: boolean,
): string {
  const { indent } = styleOf(text);
  const doc = jsonDoc(text, sequential);
  for (const op of ops) {
    if (op.kind === "delete") doc.remove([op.id], true);
    else if (!doc.edit([op.id, field], op.text))
      doc.add([op.id, field], op.text, indent);
  }
  return doc.text();
}

export function applyTableOps(
  text: string,
  ops: SourceOp[],
  map: { id: string; text: string },
): string {
  const records = parseRecords(text);
  const style = styleOf(text);
  const inline = oneRecordPerLine(text, records.length);
  let out = records.map((record) => ({ ...record }));
  for (const op of ops) {
    const index = out.findIndex((r) => String(r[map.id]) === op.id);
    if (op.kind === "delete") {
      if (index >= 0) out = out.filter((_, i) => i !== index);
    } else if (index >= 0) {
      out[index] = { ...out[index]!, [map.text]: op.text };
    } else {
      out.push({ [map.id]: op.id, [map.text]: op.text });
    }
  }
  return renderRecords(out, style, inline, text);
}

// The reader bin/gen-rails-plurals runs: the rails-i18n gem at a pinned
// version, fetched from rubygems.org and checked against its digest, its
// rails/pluralization/*.rb read for each locale's `:keys`, written
// inline or through a common module's `with_locale` (#983).
import { Buffer } from "node:buffer";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

const VERSION = "8.1.0";
const SHA256 =
  "52d5fd6c0abef28d84223cc05647f6ae0fd552637a1ede92deee9545755b6cf3";
const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "packages/adapters/src/railsplurals.ts");
const ORDER = ["zero", "one", "two", "few", "many", "other"];

const response = await globalThis.fetch(
  `https://rubygems.org/downloads/rails-i18n-${VERSION}.gem`,
);
if (!response.ok) throw new Error(`rubygems.org: ${response.status}`);
const gem = Buffer.from(await response.arrayBuffer());
const digest = createHash("sha256").update(gem).digest("hex");
if (digest !== SHA256)
  throw new Error(`rails-i18n-${VERSION}.gem: sha256 ${digest}, not ${SHA256}`);
const dir = mkdtempSync(path.join(os.tmpdir(), "rails-i18n-"));
writeFileSync(path.join(dir, "gem.tar"), gem);
execFileSync("tar", ["-xf", "gem.tar", "data.tar.gz"], { cwd: dir });
execFileSync("tar", ["-xzf", "data.tar.gz"], { cwd: dir });

const keysIn = (source) => {
  const list = /:keys\s*=>\s*\[([^\]]*)\]/.exec(source)?.[1];
  return list?.match(/:\w+/g)?.map((k) => k.slice(1));
};
const modules = new Map();
const common = path.join(dir, "lib/rails_i18n/common_pluralizations");
for (const file of readdirSync(common)) {
  const source = readFileSync(path.join(common, file), "utf8");
  const name = [...source.matchAll(/module (\w+)/g)].at(-1)?.[1];
  const keys = keysIn(source);
  if (name && keys) modules.set(name, keys);
}
const table = {};
const rules = path.join(dir, "rails/pluralization");
for (const file of readdirSync(rules).sort()) {
  const source = readFileSync(path.join(rules, file), "utf8");
  const module = /Pluralization::(\w+)\.with_locale/.exec(source)?.[1];
  const keys = module ? modules.get(module) : keysIn(source);
  if (!keys) throw new Error(`${file}: no keys read`);
  for (const k of keys)
    if (!ORDER.includes(k)) throw new Error(`${file}: key ${k}`);
  table[file.replace(/\.rb$/, "")] = ORDER.filter((c) => keys.includes(c));
}
const license = readFileSync(path.join(dir, "MIT-LICENSE.txt"), "utf8")
  .trim()
  .split("\n")
  .map((line) => `//${line ? ` ${line}` : ""}`)
  .join("\n");
const text = `// Generated by bin/gen-rails-plurals from rails-i18n ${VERSION}: do not edit.
${license}
// Each locale's plural keys as rails-i18n registers them, the categories
// its rule returns, by the locale's name as the gem spells it (#983).
export const RAILS_I18N_VERSION = "${VERSION}";

export const RAILS_PLURALS: Record<string, string[]> = {
${Object.entries(table)
  .map(
    ([locale, keys]) => `  ${JSON.stringify(locale)}: ${JSON.stringify(keys)},`,
  )
  .join("\n")}
};
`;
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error(
      `${path.relative(root, out)} is not what rails-i18n ${VERSION} gives; run bin/gen-rails-plurals`,
    );
    process.exit(1);
  }
  console.log(`${path.relative(root, out)} matches rails-i18n ${VERSION}`);
} else {
  writeFileSync(out, text);
  console.log(
    `wrote ${path.relative(root, out)}: ${Object.keys(table).length} locales`,
  );
}

// The compiler bin/gen-gettext-plurals runs: CLDR's cardinal plural rules
// (the cldr-core package, Unicode licence, pinned to the CLDR version
// Node's Intl ships) compiled into gettext's `Plural-Forms` C
// expressions (#812). gettext counts integers only, so the operands are
// read for an integer: n and i are n, every fraction operand 0. A
// language's forms are the categories integers reach, in CLDR's order.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
// The generated header names the CLDR release the package pins, as
// CLDR numbers it: major and minor.
const cldrVersion = JSON.parse(
  readFileSync(path.join(root, "node_modules/cldr-core/package.json"), "utf8"),
)
  .version.split(".")
  .slice(0, 2)
  .join(".");
const out = path.join(root, "packages/adapters/src/gettextplurals.ts");
const ORDER = ["zero", "one", "two", "few", "many", "other"];

// The integers a category is tried on, as the adapter tries them.
const INTEGERS = [
  ...Array.from({ length: 1001 }, (_, i) => i),
  1_000_000,
  2_000_000,
  10_000_000,
];

// One relation, `n % 10 = 2..4,7`, as C and as a test on an integer, or
// a constant where its operand is a fraction's, 0 for an integer.
function relation(text) {
  const m = /^([niftvwce])\s*(?:%\s*(\d+))?\s*(!=|=)\s*(.+)$/.exec(text.trim());
  if (!m) throw new Error(`relation not understood: ${text}`);
  const [, operand, mod, op, list] = m;
  const ranges = list.split(",").map((r) => {
    const [a, b] = r.trim().split("..").map(Number);
    return [a, b ?? a];
  });
  const integer = operand === "n" || operand === "i";
  const value = (n) => {
    const v = integer ? n : 0;
    return mod ? v % Number(mod) : v;
  };
  const inList = (n) => ranges.some(([a, b]) => value(n) >= a && value(n) <= b);
  const test = (n) => (op === "=" ? inList(n) : !inList(n));
  if (!integer) return { constant: test(0) };
  const x = mod ? `n%${mod}` : "n";
  const one = ([a, b]) =>
    a === b ? `${x}==${a}` : `(${x}>=${a} && ${x}<=${b})`;
  const c =
    ranges.length === 1 ? one(ranges[0]) : `(${ranges.map(one).join(" || ")})`;
  return { c: op === "=" ? c : `!${c.startsWith("(") ? c : `(${c})`}`, test };
}

// A rule, its samples cut off, as C and as a test; `and` binds tighter
// than `or`, as CLDR writes them.
function rule(text) {
  const body = text.split("@")[0].trim();
  if (body === "") return { always: true };
  const clauses = body.split(/\s+or\s+/).map((clause) => {
    const rels = clause.split(/\s+and\s+/).map(relation);
    if (rels.some((r) => r.constant === false)) return undefined;
    const live = rels.filter((r) => r.constant === undefined);
    return live;
  });
  const reachable = clauses.filter((c) => c !== undefined);
  if (reachable.length === 0) return { never: true };
  if (reachable.some((c) => c.length === 0)) return { always: true };
  const c = reachable
    .map((rels) =>
      rels.length === 1 ? rels[0].c : `(${rels.map((r) => r.c).join(" && ")})`,
    )
    .join(" || ");
  const test = (n) => reachable.some((rels) => rels.every((r) => r.test(n)));
  return { c, test };
}

function compile(cardinal) {
  const table = {};
  for (const locale of Object.keys(cardinal).sort()) {
    const rules = {};
    for (const [key, text] of Object.entries(cardinal[locale]))
      rules[key.replace("pluralRule-count-", "")] = rule(text);
    const categoryOf = (n) =>
      ORDER.find((c) => {
        const r = rules[c];
        if (!r || r.never) return false;
        return c === "other" || r.always || r.test(n);
      }) ?? "other";
    const reached = new Set(INTEGERS.map(categoryOf));
    const forms = ORDER.filter((c) => reached.has(c));
    const plural =
      forms.length === 1
        ? "0"
        : forms
            .slice(0, -1)
            .reduceRight(
              (rest, c, i) =>
                `${rules[c].always ? "1" : `(${rules[c].c})`} ? ${i} : ${rest}`,
              String(forms.length - 1),
            );
    table[locale] = { nplurals: forms.length, plural, forms };
  }
  return table;
}

function render(table) {
  const rows = Object.entries(table)
    .map(
      ([locale, { nplurals, plural, forms }]) =>
        `  ${JSON.stringify(locale)}: {\n    nplurals: ${nplurals},\n    plural: ${JSON.stringify(plural)},\n    forms: ${JSON.stringify(forms)},\n  },`,
    )
    .join("\n");
  return `// Generated by bin/gen-gettext-plurals from CLDR ${cldrVersion} (cldr-core):
// do not edit. Copyright © 2004-2025 Unicode, Inc. Unicode License v3,
// https://www.unicode.org/license.txt.
// Each language's gettext \`Plural-Forms\`, its forms the CLDR categories
// integers reach, in CLDR's order (#812).
export const GETTEXT_PLURALS: Record<
  string,
  { nplurals: number; plural: string; forms: string[] }
> = {
${rows}
};
`;
}

{
  const cardinal = JSON.parse(
    readFileSync(
      path.join(root, "node_modules/cldr-core/supplemental/plurals.json"),
      "utf8",
    ),
  ).supplemental["plurals-type-cardinal"];
  const text = render(compile(cardinal));
  if (process.argv.includes("--check")) {
    if (readFileSync(out, "utf8") !== text) {
      console.error(
        `${path.relative(root, out)} is not what CLDR compiles to; run bin/gen-gettext-plurals`,
      );
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(
      `wrote ${path.relative(root, out)}: ${Object.keys(cardinal).length} locales`,
    );
  }
}
